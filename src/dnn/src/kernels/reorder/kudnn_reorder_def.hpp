template <typename InType, typename OutType>
void FastReorder(const Shape &start, const Shape &end, const InType *typedSrc, OutType *typedDst,
    SizeType strideIn, SizeType strideOut) noexcept
{
    for (SizeType batch = start[IDX_2]; batch < end[IDX_2]; batch++) {
        for (SizeType ih = start[IDX_3]; ih < end[IDX_3]; ih += BLOCK_SIZE) {
            SizeType maxIh = std::min(ih + BLOCK_SIZE, end[IDX_3]);
            for (SizeType iw = start[IDX_4]; iw < end[IDX_4]; iw += BLOCK_SIZE) {
                SizeType maxIw = std::min(iw + BLOCK_SIZE, end[IDX_4]);
                for (SizeType localIh = ih; localIh < maxIh; localIh += REORDER_UNROLL) {
                    SizeType residIh = std::min(REORDER_UNROLL, maxIh - localIh) - 1;
                    for (SizeType localIw = iw; localIw < maxIw; localIw += REORDER_UNROLL) {
                        SizeType residIw = std::min(REORDER_UNROLL, maxIw - localIw) - 1;
                        // It was done to obtain better perf:
#ifdef KUDNNL_920Pro
                        if constexpr (std::is_same_v<InType, float> || std::is_same_v<InType, std::int32_t>) {
                            TRANSPOSE_REORDER_FUNC_ARR[residIh * REORDER_UNROLL + residIw](
                                typedSrc + (batch * strideOut + localIh) * strideIn + localIw,
                                typedDst + (batch * strideIn + localIw) * strideOut + localIh,
                                strideIn * sizeof(InType), strideOut * sizeof(OutType), 1.0f);
                        } else {
                            TRANSPOSE_REORDER_FUNC_ARR_B[residIh * REORDER_UNROLL + residIw](
                                typedSrc + (batch * strideOut + localIh) * strideIn + localIw,
                                typedDst + (batch * strideIn + localIw) * strideOut + localIh,
                                strideIn * sizeof(InType), strideOut * sizeof(OutType), 1.0f);
                        }
#else // KUDNNL_920Pro
                        TRANSPOSE_REORDER_FUNC_ARR[residIh * REORDER_UNROLL + residIw](
                            typedSrc + (batch * strideOut + localIh) * strideIn + localIw,
                            typedDst + (batch * strideIn + localIw) * strideOut + localIh,
                            strideIn * sizeof(InType), strideOut * sizeof(OutType), 1.0f);
#endif // KUDNNL_920Pro
                    }
                }
            }
        }
    }
}

template <typename InType, typename OutType>
struct ReorderNLoop final {
    static SizeType LoopInc() noexcept
    {
        return 1;
    }
    static void Do(SizeType loopIdx, SizeType loopRange, const InType *typedSrc,
        OutType *typedDst, SizeType dstStride, SizeType srcIdx, SizeType dstIdx) noexcept
    {
        Service::Unused(loopRange);
        typedDst[dstIdx + loopIdx * dstStride] =
            Vector::Convert<InType, OutType>::Do(typedSrc[srcIdx + loopIdx]);
    }
};

template <typename InType, typename OutType>
void SimpleReorder(const Shape &start, const Shape &end, const InType *typedSrc, OutType *typedDst,
    const Shape &reorderedStridesSrc, const Shape &reorderedStridesDst) noexcept
{
    for (SizeType a = start[IDX_0]; a < end[IDX_0]; a++) {
        SizeType srcIdx0 = a * reorderedStridesSrc[IDX_0];
        SizeType dstIdx0 = a * reorderedStridesDst[IDX_0];
        for (SizeType b = start[IDX_1]; b < end[IDX_1]; b++) {
            SizeType srcIdx1 = b * reorderedStridesSrc[IDX_1];
            SizeType dstIdx1 = b * reorderedStridesDst[IDX_1];
            for (SizeType c = start[IDX_2]; c < end[IDX_2]; c++) {
                SizeType srcIdx2 = c * reorderedStridesSrc[IDX_2];
                SizeType dstIdx2 = c * reorderedStridesDst[IDX_2];
                for (SizeType d = start[IDX_3]; d < end[IDX_3]; d++) {
                    SizeType srcIdx = srcIdx0 + srcIdx1 + srcIdx2 + d * reorderedStridesSrc[IDX_3];
                    SizeType dstIdx = dstIdx0 + dstIdx1 + dstIdx2 + d * reorderedStridesDst[IDX_3];
                    Service::UnrollFor::Do<NUM_1>(start[IDX_4], end[IDX_4], ReorderNLoop<InType, OutType>{},
                        typedSrc, typedDst, reorderedStridesDst[IDX_4], srcIdx, dstIdx);
                }
            }
        }
    }
}

template <typename InType, typename OutType>
void EvaluateReorder(const Shape &start, const Shape &end, const InType *typedSrc, OutType *typedDst,
    const Shape &reorderedStridesSrc, const Shape &reorderedStridesDst,
    bool fastReorder, SizeType strideIn, SizeType strideOut) noexcept
{
    bool isFastType = false;
#ifdef KUDNNL_920Pro
    isFastType = (std::is_same_v<InType, float> && std::is_same_v<OutType, float>) ||
        (std::is_same_v<InType, std::int8_t> && std::is_same_v<OutType, std::int8_t>) ||
        (std::is_same_v<InType, std::uint8_t> && std::is_same_v<OutType, std::uint8_t>) ||
        (std::is_same_v<InType, std::int32_t> && std::is_same_v<OutType, std::int32_t>);
#else // KUDNNL_920Pro
    isFastType = (std::is_same_v<InType, float> && std::is_same_v<OutType, float>);
#endif // KUDNNL_920Pro
    if (isFastType && fastReorder) {
        FastReorder(start, end, typedSrc, typedDst, strideIn, strideOut);
    } else {
        SimpleReorder(start, end, typedSrc, typedDst, reorderedStridesSrc, reorderedStridesDst);
    }
}

